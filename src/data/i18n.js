export function getT(langCode) {
  if (!langCode || langCode === 'en') return (key) => strings.en[key] || key
  const parts = langCode.split('-')
  if (parts.length === 2) {
    const [a, b] = parts
    return (key) => {
      const va = strings[a]?.[key] || strings.en[key] || key
      const vb = strings[b]?.[key] || strings.en[key] || key
      if (va === vb) return va
      return `${va}\n${vb}`
    }
  }
  return (key) => strings[langCode]?.[key] || strings.en[key] || key
}

export function getNames(langCode) {
  if (!langCode || langCode === 'en') return localNames.en
  const parts = langCode.split('-')
  const primary = parts[0]
  return localNames[primary] || localNames.en
}
